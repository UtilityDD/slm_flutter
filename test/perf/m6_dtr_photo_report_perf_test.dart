// m6_dtr_photo_report (lesson 6.1 কাজ 1 "দু'মিনিটের ছবি-রিপোর্ট") at rest:
// once the guide has read the JE's request, the scene, the viewfinder, the
// live view, the zoom rail and the photo tray draw nothing while the player
// thinks — with animations and with reduced motion; and again after a far
// shot (the JE's reply up, still).
import 'dart:math' as math;

import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
