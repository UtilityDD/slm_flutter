// m6_ab_unjam (lesson 6.4 কাজ 2 "জ্যাম ছাড়াও, লাইন জোড়ো") at rest: once the
// guide has said the task, the switch head, the pouch and the docket draw
// nothing while the player thinks — with animations and with reduced motion;
// and again after a rock of the lever (a one-shot) and with the can in hand.
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
