// m6_fuse_gauge (lesson 6.3 কাজ 1 "মেপে তবেই বাঁধো") at rest: once the guide
// has said the task, the bench, the plate, the reels and the carrier draw
// nothing while the player thinks — with animations and with reduced motion;
// and again after a probe (the fit chip comes and goes, then still).
import 'dart:math' as math;

