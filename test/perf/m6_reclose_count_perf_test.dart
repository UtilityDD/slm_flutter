// m6_reclose_count (lesson 6.8 কাজ 1 "চেষ্টা গুনুন") at rest: once the guide
// has said the task, the storm field, the pole, the van's board, the docket
// and the tally draw nothing while the player thinks — with animations and
// with reduced motion; and again after the docket is away and the cycle has
// run to its end (the lights hold still, no timer left running).
import 'dart:math' as math;

import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:slm_flutter/features/game/content_catalog.dart';
import 'package:slm_flutter/features/game/level_shell.dart';
