// m6_meter_swap_proof (lesson 6.10 কাজ 2 "মিটার বদল, ছবিতে প্রমাণ") at rest:
// once the guide has said the task, the wall, the decision buttons and the
// docket draw nothing while the player thinks — with animations and with
// reduced motion; and again after a close look (it closes by itself) and a
// seal tug.
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
