// m6_capbank_wait (lesson 6.7 কাজ 1 "ঘড়ি ধরে অপেক্ষা") at rest: once the
// switch is OFF and the guide has said the task, the pole, the bank and the
// watch draw nothing while the player waits — the watch's minute hand moves
// once a game minute (every 2.5 s, a repaint of its own boundary, no widget
// rebuild), with animations and with reduced motion; and again with the rod
// in hand.
import 'dart:math' as math;

import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
