// m6_abc_nick_seal (lesson 6.6 কাজ 2 "কাটা আবরণ সিল করো") at rest: once the
// guide has said the task, the span, the dockets and the tray draw nothing
// while the player looks — with animations and with reduced motion; and again
// after a double-tap zoom (a one-shot).
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';
