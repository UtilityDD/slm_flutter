// m7_claim_route (lesson 7.2 কাজ 2 "দাবির পথ") at rest: once the ride is over
// and the late-call card is up, and again on the town map while he waits to
// be dragged, nothing draws while the player reads — with animations and with
// reduced motion.
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
