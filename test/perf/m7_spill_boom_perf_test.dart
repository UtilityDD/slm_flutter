// m7_spill_boom (lesson 7.8 কাজ 1 "এক ফোঁটাও মাটিতে নয়") at rest: once the
// guide has said the task, the yard (the DTR, the kit, the containers, the drain)
// draws nothing while the player thinks — with animations and with reduced
// motion; and again after the kit is tapped open (a one-shot).
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';
