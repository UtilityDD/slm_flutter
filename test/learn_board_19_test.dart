  test("every SVG of this board's rounds in the storm_board folder is a card on the board", () {
    final used = {for (final s in pack.slots) for (final o in s.options) o.asset};
    final rounds = {for (final s in pack.slots) s.id};
    final onDisk = Directory(_artDir)
        .listSync()
        .whereType<File>()
        .map((f) => f.uri.pathSegments.last)
        .where((n) => n.endsWith('.svg') && rounds.contains(n.split('_').first))
