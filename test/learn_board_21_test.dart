  test('the lesson\'s points: VDE 1000V, right tool for right job, nicks, size, tester limits', () {
    // Pliers: VDE 1000V, no cracked/burnt handle, Pliers = Hammer নয়.
    expect(_reject('pliers', 'bare'), contains('VDE 1000V'));
    expect(_reject('pliers', 'cracked'), contains('ফাটলে ব্যবহার নয়'));
    expect(_reject('pliers', 'burnt'), contains('পোড়া'));
    expect(_reject('pliers', 'hammer'), contains('Pliers = Hammer নয়'));
    // Strip: a knife / ordinary pliers nicks the conductor; blunt cutter; both VDE.
    expect(_reject('strip', 'knife'), allOf(contains('Nick'), contains('Hot Spot')));
    expect(_reject('strip', 'pliers'), contains('Nick'));
    expect(_reject('strip', 'blunt'), contains('ভোঁতা'));
    expect(_reject('strip', 'bare'), contains('দুটোই VDE 1000V'));
    // Screwdrivers: wrong size slips; insulated to the blade root; not a chisel.
    expect(_reject('screw', 'small'), allOf(contains('ভুল Size'), contains('Short Circuit')));
    expect(_reject('screw', 'bare'), contains('Metal Tip'));
    expect(_reject('screw', 'chisel'), contains('Screwdriver = Chisel নয়'));
    expect(_reject('screw', 'bent'), contains('Tip'));
    // Spanners: loose / worn slips — worst on a pole.
    expect(_reject('spanner', 'loose'), contains('Pole-এ বিশেষ বিপজ্জনক'));
    expect(_reject('spanner', 'worn'), contains('ক্ষয়ে'));
    // Tester: phase only; neutral/earth need a multimeter; LV only.
    expect(_reject('tester', 'neutral'), contains('Multimeter'));
    expect(_reject('tester', 'earth'), contains('Multimeter'));
    expect(_reject('tester', 'ht'), contains('~500V'));
    expect(_slot('tester').whyChips.any((w) => w.correct && w.textBn.contains('জানা লাইভ পয়েন্টে')), isTrue);
    expect(pack.earnedBn, contains('গ্লাভস + VDE'));
