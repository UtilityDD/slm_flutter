"""Learn voice pack: every fixed coach line in the coach's voice (same Edge
neural voice and prosody as the Duty Slip clips), and the rival in a clearly
different one.

1. flutter test tool/dump_learn_voice_lines_test.dart   (writes tool/learn_voice_lines.json)
2. python -I tool/make_learn_voice.py

Writes assets/sounds/learn_voice/*.mp3 (mono 24 kHz, re-encoded to 32 kbps by tool/voice_32k.py) and the generated
lib/features/game/learn_voice_map.dart. Existing clips are kept; clips for
lines that are gone are deleted.
"""

import asyncio
import hashlib
import json
import os
import sys

import edge_tts
try:
    from tool.voice_32k import to_32k
except ImportError:  # run as a plain script from tool/
    from voice_32k import to_32k

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
LINES = os.path.join(ROOT, "tool", "learn_voice_lines.json")
OUT = os.path.join(ROOT, "assets", "sounds", "learn_voice")
DART = os.path.join(ROOT, "lib", "features", "game", "learn_voice_map.dart")

# Must match tool/slm_game_voice_library.py (the coach's recorded voice).
COACH = ("bn-IN-BashkarNeural", "-1%", "+0Hz")
# Rival: another speaker, slower and lower, so he never sounds like the coach.
RIVAL = ("bn-BD-PradeepNeural", "-6%", "-14Hz")


def _name(prefix, key):
    return f"{prefix}_{hashlib.sha1(key.encode('utf-8')).hexdigest()[:10]}.mp3"


async def _make(sem, text, path, voice):
    name, rate, pitch = voice
    async with sem:
        for attempt in range(3):
            try:
                await edge_tts.Communicate(text, name, rate=rate, pitch=pitch).save(path)
                to_32k(path)  # app standard: 32 kbps mono 24 kHz
                return
            except Exception as e:  # network hiccups
                if attempt == 2:
                    raise RuntimeError(f"{os.path.basename(path)}: {e}") from e
                await asyncio.sleep(1.5)


def _dart_str(s):
    return json.dumps(s, ensure_ascii=False).replace("$", "\\$")


async def main():
    with open(LINES, encoding="utf-8") as f:
        data = json.load(f)
    os.makedirs(OUT, exist_ok=True)
    sem = asyncio.Semaphore(4)
    jobs, maps, keep = [], {"coach": {}, "rival": {}}, set()
    for group, prefix, voice in (("coach", "c", COACH), ("rival", "r", RIVAL)):
        for row in data[group]:
            file = _name(prefix, row["key"])
            keep.add(file)
            maps[group][row["key"]] = f"sounds/learn_voice/{file}"
            path = os.path.join(OUT, file)
            if not os.path.exists(path) or os.path.getsize(path) == 0:
                jobs.append(_make(sem, row["say"], path, voice))
    print(f"generating {len(jobs)} clips…")
    await asyncio.gather(*jobs)
    for f in os.listdir(OUT):
        if f not in keep:
            os.remove(os.path.join(OUT, f))

    out = [
        "// GENERATED by tool/make_learn_voice.py — do not edit by hand.",
        "// Line text -> recorded clip (under assets/).",
        "",
    ]
    for group, var in (("coach", "learnCoachVoice"), ("rival", "learnRivalVoice")):
        out.append(f"const {var} = <String, String>{{")
        for k in sorted(maps[group]):
            out.append(f"  {_dart_str(k)}: '{maps[group][k]}',")
        out.append("};")
        out.append("")
    with open(DART, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    total = sum(os.path.getsize(os.path.join(OUT, f)) for f in keep)
    print(f"coach {len(maps['coach'])}, rival {len(maps['rival'])}, {total // 1024} KB")


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
