"""
SLM Voice System: Dart Code Generator.

Syncs all generated audio cues into Flutter code:
1. lib/features/duty_slip/duty_slip_voice.dart
2. lib/features/game/learn_voice_map.dart
"""

import json
import os
import sys

from tool.voice_system.catalog import ROOT_DIR, get_all_cues, load_duty_slip_cues, load_guide_cues, load_learn_voice_cues


def _dart_str(s: str) -> str:
    """Escapes string for Dart double-quoted literal."""
    return json.dumps(s, ensure_ascii=False).replace("$", "\\$")


def generate_learn_voice_map(output_path: str = None) -> str:
    """Generates lib/features/game/learn_voice_map.dart."""
    if not output_path:
        output_path = os.path.join(ROOT_DIR, "lib", "features", "game", "learn_voice_map.dart")

    json_path = os.path.join(ROOT_DIR, "tool", "learn_voice_lines.json")
    if not os.path.exists(json_path):
        return ""

    with open(json_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    learn_cues = load_learn_voice_cues()

    coach_entries = []
    for item in data.get("coach", []):
        t_clean = (item["say"] if isinstance(item, dict) else str(item)).strip()
        import hashlib
        h = hashlib.sha1(t_clean.encode("utf-8")).hexdigest()[:10]
        key = f"c_{h}"
        asset_rel = f"sounds/learn_voice/{key}.mp3"
        coach_entries.append((t_clean, asset_rel))

    rival_entries = []
    for item in data.get("rival", []):
        t_clean = (item["say"] if isinstance(item, dict) else str(item)).strip()
        import hashlib
        h = hashlib.sha1(t_clean.encode("utf-8")).hexdigest()[:10]
        key = f"r_{h}"
        asset_rel = f"sounds/learn_voice/{key}.mp3"
        rival_entries.append((t_clean, asset_rel))

    lines = [
        "// GENERATED by tool/voice_system/dart_codegen.py — do not edit by hand.",
        "// Line text -> recorded clip (under assets/).",
        "",
        "const learnCoachVoice = <String, String>{",
    ]
    for text, path in coach_entries:
        lines.append(f"  {_dart_str(text)}: '{path}',")
    lines.append("};")
    lines.append("")
    lines.append("const learnRivalVoice = <String, String>{")
    for text, path in rival_entries:
        lines.append(f"  {_dart_str(text)}: '{path}',")
    lines.append("};")
    lines.append("")

    content = "\n".join(lines)
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(content)
    return output_path


def generate_duty_slip_voice(output_path: str = None) -> str:
    """Updates lib/features/duty_slip/duty_slip_voice.dart with all guide & level cues."""
    if not output_path:
        output_path = os.path.join(ROOT_DIR, "lib", "features", "duty_slip", "duty_slip_voice.dart")

    from tool.update_duty_slip_voice_dart import CATALOG_PATH, LEGACY_VARIANTS

    with open(CATALOG_PATH, "r", encoding="utf-8") as f:
        catalog = json.load(f)

    guide_cues = load_guide_cues()

    audio_map = {}

    # 1. Guide Cues (both key and full text)
    for cue_id, cue in guide_cues.items():
        rel_path = f"sounds/guide_voice/{cue_id}.mp3"
        audio_map[cue_id] = rel_path
        if cue.original_text:
            audio_map[cue.original_text] = rel_path
        if cue.normalized_text and cue.normalized_text != cue.original_text:
            audio_map[cue.normalized_text] = rel_path

    # 2. Level Cues from catalog
    for section_key, section in catalog.items():
        cues = section.get("cues", {})
        for cue_id, cue_data in cues.items():
            rel_path = f"sounds/voice/{cue_id}.mp3"
            audio_map[cue_id] = rel_path
            new_text = cue_data.get("text", "")
            if new_text:
                audio_map[new_text] = rel_path
            old_text = cue_data.get("old", "")
            if old_text and old_text != new_text:
                audio_map[old_text] = rel_path

    # 3. Legacy Variants
    for variant_text, rel_path in LEGACY_VARIANTS.items():
        if variant_text not in audio_map:
            audio_map[variant_text] = rel_path

    # Read existing template / class methods
    with open(output_path, "r", encoding="utf-8") as f:
        existing = f.read()

    # Find where _audioMap begins and ends
    start_marker = "  static const _audioMap = <String, String>{"
    end_marker = "  };\n\n  /// Plays a voice cue"

    if start_marker not in existing or end_marker not in existing:
        print("[WARNING] Could not locate _audioMap markers in duty_slip_voice.dart", file=sys.stderr)
        return ""

    map_lines = [start_marker]
    for key, path in audio_map.items():
        map_lines.append(f"    {_dart_str(key)}: '{path}',")
    map_lines.append("  };\n\n  /// Plays a voice cue")

    new_map_str = "\n".join(map_lines)
    pre = existing[: existing.find(start_marker)]
    post = existing[existing.find(end_marker) + len("  };\n\n  /// Plays a voice cue") :]

    new_content = pre + new_map_str + post
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(new_content)
    return output_path

