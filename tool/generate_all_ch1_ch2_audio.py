async def process_chapter(ch):
    cid = ch["id"]
    title = ch["title"]
    print(f"\n>>> Processing {cid}: {title} ({len(ch['segments'])} segments)...")
    ch_dir = os.path.join(TEMP_BASE, cid)
    os.makedirs(ch_dir, exist_ok=True)
    
    seg_wavs = []
    for idx, text in enumerate(ch["segments"]):
        seg_mp3 = os.path.join(ch_dir, f"seg_{idx}.mp3")
        seg_wav = os.path.join(ch_dir, f"seg_{idx}.wav")
        communicate = edge_tts.Communicate(text, VOICE, rate=RATE, pitch=PITCH)
        await communicate.save(seg_mp3)
        
        cmd = [FFMPEG_EXE, "-y", "-i", seg_mp3, "-ar", "44100", "-ac", "2", seg_wav]
        subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
        seg_wavs.append(seg_wav)
        
    concat_list = os.path.join(ch_dir, "concat.txt")
    with open(concat_list, "w", encoding="utf-8") as f:
        for idx, w in enumerate(seg_wavs):
            f.write(f"file '{w.replace(chr(92), '/')}'\n")
            if idx < len(seg_wavs) - 1:
                f.write(f"file '{SILENCE_WAV.replace(chr(92), '/')}'\n")
                
    master_wav = os.path.join(ch_dir, "master.wav")
    out_mp3_name = f"{cid}_portrait.mp3"
    out_mp3 = os.path.join(OUT_DIR, out_mp3_name)
    
    subprocess.run([
        FFMPEG_EXE, "-y", "-f", "concat", "-safe", "0", "-i", concat_list,
        "-c:a", "pcm_s16le", master_wav
    ], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
    
    subprocess.run([
        FFMPEG_EXE, "-y", "-i", master_wav, "-b:a", "192k", out_mp3
    ], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
    
    # Also save an artifact copy
    artifact_mp3 = os.path.join(ARTIFACT_DIR, out_mp3_name)
    shutil.copy2(out_mp3, artifact_mp3)
    
    # Measure duration
    res = subprocess.run([FFMPEG_EXE, "-i", out_mp3], stderr=subprocess.PIPE, text=True)
    dur_str = "unknown"
    for line in res.stderr.splitlines():
        if "Duration:" in line:
            dur_str = line.split("Duration:")[1].split(",")[0].strip()
            break
            
    print(f"  [DONE] {cid}: {out_mp3_name} | Duration: {dur_str} | Size: {os.path.getsize(out_mp3):,} bytes")
    return {
        "id": cid,
        "title": title,
        "filename": out_mp3_name,
        "duration": dur_str,
        "size": os.path.getsize(out_mp3)
    }

